create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique not null,
  role text not null default 'user' check (role in ('admin','user')),
  created_at timestamptz not null default now()
);
create table if not exists public.app_versions (
  id bigint generated by default as identity primary key,
  name text not null,
  tag text not null,
  notes text not null,
  download_url text not null check (download_url ~ '^https?://'),
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.profiles enable row level security;
alter table public.app_versions enable row level security;

-- Profile dibuat otomatis sebagai user saat akun Auth baru dibuat.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare uname text;
begin
  uname := coalesce(new.raw_user_meta_data ->> 'username', split_part(new.email,'@',1));
  insert into public.profiles (id, username, role)
  values (new.id, uname, 'user')
  on conflict (id) do nothing;
  return new;
end;
$$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = ''
as $$
  select exists (select 1 from public.profiles where id = (select auth.uid()) and role = 'admin');
$$;

drop policy if exists "profiles read own" on public.profiles;
create policy "profiles read own" on public.profiles for select to authenticated using (id = (select auth.uid()) or public.is_admin());
-- Tidak ada policy update/insert/delete untuk profiles. User tidak dapat menaikkan role sendiri.

drop policy if exists "authenticated read versions" on public.app_versions;
create policy "authenticated read versions" on public.app_versions for select to authenticated using (true);
drop policy if exists "admin insert versions" on public.app_versions;
create policy "admin insert versions" on public.app_versions for insert to authenticated with check (public.is_admin() and created_by = (select auth.uid()));
drop policy if exists "admin update versions" on public.app_versions;
create policy "admin update versions" on public.app_versions for update to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists "admin delete versions" on public.app_versions;
create policy "admin delete versions" on public.app_versions for delete to authenticated using (public.is_admin());

grant usage on schema public to anon, authenticated;
grant select on public.app_versions to authenticated;
grant insert, update, delete on public.app_versions to authenticated;
grant select on public.profiles to authenticated;
grant usage, select on sequence public.app_versions_id_seq to authenticated;
